"""Sync guard for the committed scene catalog artifact.

``ui/scenes.json`` is generated by ``scripts/export_scenes.py`` from the domain
catalog in ``gestor_luces/domain/scenes.py``. The frontend reads that JSON at
startup instead of keeping a second hardcoded copy. This test fails whenever the
domain and the committed JSON diverge, so the catalog stays a single source.
"""

from __future__ import annotations

import json

from gestor_luces.domain.scenes import BUILTIN_SCENES
from gestor_luces.main import resolve_ui_directory

_REGENERATE_HINT = "corré `python scripts/export_scenes.py`"


def _expected_payload() -> list[dict[str, object]]:
    return [scene.to_dict() for scene in BUILTIN_SCENES]


def test_scenes_json_matches_domain_catalog() -> None:
    """The committed ui/scenes.json must be byte-for-byte the domain catalog."""
    path = resolve_ui_directory() / "scenes.json"
    assert path.is_file(), f"Missing {path}; {_REGENERATE_HINT}"

    committed = json.loads(path.read_text(encoding="utf-8"))
    expected = _expected_payload()

    assert committed == expected, (
        f"ui/scenes.json está desincronizado del dominio; {_REGENERATE_HINT}"
    )


def test_scenes_json_is_exactly_36_ordered_scenes() -> None:
    """Defensive shape check: 36 scenes, ordered by id, with the UI's keys only."""
    path = resolve_ui_directory() / "scenes.json"
    committed = json.loads(path.read_text(encoding="utf-8"))

    assert len(committed) == 36, f"Expected 36 scenes, got {len(committed)}; {_REGENERATE_HINT}"
    assert [item["scene_id"] for item in committed] == list(range(1, 37)), (
        f"Scenes must be ordered 1..36; {_REGENERATE_HINT}"
    )

    expected_keys = {"scene_id", "name", "category", "supports_speed"}
    for item in committed:
        assert set(item.keys()) == expected_keys, (
            f"Unexpected keys {sorted(item.keys())}; {_REGENERATE_HINT}"
        )

    # The exporter must serialize every domain scene, not a subset.
    domain_ids = {scene.scene_id for scene in BUILTIN_SCENES}
    assert {item["scene_id"] for item in committed} == domain_ids, _REGENERATE_HINT
